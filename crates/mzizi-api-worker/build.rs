//! Packs the bundled registry data (`src/data/*.json`, from
//! `npm run build:data`) so a cold isolate parses only what a request reads.
//!
//! The Worker used to embed the JSON files as they are and parse a whole file
//! on first use: `/v1/ui/{name}` on a fresh isolate parsed `components.json`
//! (1 MB) and `sources.json` (4 MB) to answer for one component, inside the
//! request's CPU time. Under a burst, every new isolate paid that. Here:
//!
//! - Keyed files (sources, binary files, Astro documents, docs rows, full
//!   items, skills, changelog versions) become one blob of JSON values plus a
//!   sorted `(key, start, end)` table, so a lookup is a binary search and the
//!   parse of that one value.
//! - The index routes (`/v1/ui`, `/v1/search`) read a slim copy of the items
//!   with only the fields they serve, a third of `components.json`.
//! - `meta.json` becomes constants: the pin, the rename table, the crate git
//!   URL, the item count and the OpenAPI YAML as text.
//! - Files that are read whole by one route (helix, doctrine, brand, samples,
//!   changelog entries, the skills list) are written alone, so that route
//!   parses only its own file.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value, json};

const FILES: &[&str] = &[
    "ai-instruction-index.json",
    "astro.json",
    "binary.json",
    "brand.json",
    "changelog.json",
    "component-docs.json",
    "components.json",
    "doctrine.json",
    "helix.json",
    "meta.json",
    "samples.json",
    "skills.json",
    "sources.json",
];

fn read(dir: &Path, file: &str) -> Value {
    let path = dir.join(file);
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn object(v: Value, what: &str) -> Map<String, Value> {
    match v {
        Value::Object(m) => m,
        _ => panic!("{what}: expected a JSON object"),
    }
}

/// Writes `name.blob` and returns the Rust expression of a `Packed` table over it.
fn pack(out: &Path, name: &str, entries: impl IntoIterator<Item = (String, Value)>) -> String {
    // A later duplicate key wins, as `new Map(entries)` and object spread do.
    let sorted: BTreeMap<String, Value> = entries.into_iter().collect();
    let mut blob = String::new();
    let mut index = String::new();
    for (key, value) in &sorted {
        let start = blob.len();
        blob.push_str(&serde_json::to_string(value).expect("serialize"));
        write!(index, "({key:?}, {start}, {}),", blob.len()).unwrap();
    }
    fs::write(out.join(format!("{name}.blob")), blob).unwrap();
    format!(
        "Packed {{ blob: include_str!(concat!(env!(\"OUT_DIR\"), \"/{name}.blob\")), index: &[{index}] }}"
    )
}

fn write_json(out: &Path, name: &str, value: &Value) {
    fs::write(out.join(name), serde_json::to_string(value).unwrap()).unwrap();
}

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/data");
    for file in FILES {
        let path = dir.join(file);
        println!("cargo::rerun-if-changed={}", path.display());
        assert!(
            path.exists(),
            "{} is missing. Run `npm ci && npm run build:data` at the repository root first: \
             the Worker embeds the registry data that step generates.",
            path.display()
        );
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let mut code = String::from("// Generated by build.rs from src/data/*.json.\n");

    // meta.json → constants.
    let meta = object(read(&dir, "meta.json"), "meta.json");
    let text = |k: &str| {
        meta[k]
            .as_str()
            .unwrap_or_else(|| panic!("meta.{k}"))
            .to_owned()
    };
    fs::write(out.join("openapi.yaml"), text("openapiYaml")).unwrap();
    let mut renames: Vec<(String, String)> = meta["renames"]
        .as_object()
        .expect("meta.renames")
        .iter()
        .map(|(k, v)| (k.clone(), v.as_str().expect("rename").to_owned()))
        .collect();
    renames.sort();
    writeln!(code, "pub const REGISTRY_REF: &str = {:?};", text("ref")).unwrap();
    writeln!(code, "pub const CRATE_GIT: &str = {:?};", text("crateGit")).unwrap();
    writeln!(
        code,
        "pub static OPENAPI_YAML: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/openapi.yaml\"));"
    )
    .unwrap();
    code.push_str("pub static RENAMES: &[(&str, &str)] = &[");
    for (from, to) in &renames {
        write!(code, "({from:?}, {to:?}),").unwrap();
    }
    code.push_str("];\n");

    // components.json → the full items by name, and the slim index.
    let Value::Array(items) = read(&dir, "components.json") else {
        panic!("components.json: expected an array")
    };
    writeln!(code, "pub const COMPONENT_COUNT: usize = {};", items.len()).unwrap();
    let slim: Vec<Value> = items
        .iter()
        .map(|item| {
            let mut s = Map::new();
            for k in [
                "name",
                "type",
                "title",
                "description",
                "categories",
                "dependencies",
                "registryDependencies",
                "node",
                "nodeLabel",
                "rsPath",
            ] {
                if let Some(v) = item.get(k) {
                    s.insert(k.to_owned(), v.clone());
                }
            }
            if let Some(m) = item.get("meta").and_then(Value::as_object) {
                let mut meta = Map::new();
                for k in ["owner", "collection"] {
                    if let Some(v) = m.get(k) {
                        meta.insert(k.to_owned(), v.clone());
                    }
                }
                s.insert("meta".into(), Value::Object(meta));
            }
            Value::Object(s)
        })
        .collect();
    write_json(&out, "components-index.json", &Value::Array(slim));
    let by_name = items.into_iter().map(|item| {
        let name = item["name"].as_str().expect("item.name").to_owned();
        (name, item)
    });
    writeln!(
        code,
        "pub static ITEMS: Packed = {};",
        pack(&out, "items", by_name)
    )
    .unwrap();

    for (file, name) in [
        ("sources.json", "SOURCES"),
        ("binary.json", "BINARY"),
        ("astro.json", "ASTRO"),
        ("component-docs.json", "COMPONENT_DOCS"),
    ] {
        let entries = object(read(&dir, file), file);
        let packed = pack(&out, &name.to_lowercase(), entries);
        writeln!(code, "pub static {name}: Packed = {packed};").unwrap();
    }

    // changelog.json → the entries alone, and the versions packed.
    let mut changelog = object(read(&dir, "changelog.json"), "changelog.json");
    write_json(&out, "changelog-entries.json", &changelog["entries"]);
    let versions = object(
        changelog.remove("byVersion").expect("byVersion"),
        "byVersion",
    );
    writeln!(
        code,
        "pub static CHANGELOG_VERSIONS: Packed = {};",
        pack(&out, "changelog_versions", versions)
    )
    .unwrap();

    // skills.json → the list, names and version, and each skill packed.
    let mut skills = object(read(&dir, "skills.json"), "skills.json");
    let by_name = object(skills.remove("byName").expect("byName"), "byName");
    writeln!(
        code,
        "pub static SKILLS: Packed = {};",
        pack(&out, "skills", by_name)
    )
    .unwrap();
    write_json(
        &out,
        "skills-list.json",
        &json!({ "list": skills["list"], "names": skills["names"], "version": skills["version"] }),
    );

    fs::write(out.join("bundle.rs"), code).unwrap();
}
